import { Typography, Stack, TextField, Button, Box } from '@material-ui/core';
import Page from 'components/Page';
import useAuth from 'hooks/useAuth';
import { useSnackbar } from 'notistack5';
import { useEffect, useState } from 'react';
import axios from 'utils/axios';
import QRCode from 'react-qr-code';

function Verify2FA() {
  const { user } = useAuth();
  const [code, setCode] = useState('');
  const { enqueueSnackbar } = useSnackbar();
  const { setIsOtpVerified } = useAuth();
  const [qrCode, setQrCode] = useState<string>('');

  useEffect(() => {
    axios
      .post(`otp_secrets.json`)
      .then((response) => {
        setQrCode(response.data.qr_link);
      })
      .catch((error) => {
        enqueueSnackbar('Something went wrong!', { variant: 'error' });
      });
  }, []);

  const handleVerifyCode = () => {
    axios
      .post(`otp_secrets/verify.json`, {
        otp_code: code
      })
      .then((response) => {
        setIsOtpVerified();
        enqueueSnackbar('Successfully verified!', { variant: 'success' });
      })
      .catch((error) => {
        enqueueSnackbar('Something went wrong!', { variant: 'error' });
      });
  };

  const handleCancelCode = () => {
    axios
      .delete(`verification_codes/abc.json`)
      .then((response) => {})
      .catch((error) => {
        enqueueSnackbar('Something went wrong!', { variant: 'error' });
      });
  };

  const handleCodeChange = (value: string) => {
    if (value?.length <= 6) {
      setCode(value);
    }
  };

  return (
    <Page
      title="Sphere | Verification"
      sx={{
        display: 'flex',
        justifyContent: 'center',
        alignItems: 'center',
        backgroundColor: '#12125C',
        width: '100%',
        height: '100%',
        padding: '0px 10px'
      }}
    >
      <Stack spacing={2} alignItems="center">
        {!user?.is_qr_scanned && (
          <Box
            sx={{
              padding: '8px',
              paddingBottom: '2px!important',
              backgroundColor: '#fff',
              borderRadius: '5px'
            }}
          >
            <QRCode value={qrCode} size={75} viewBox="0 0 75 75" />
          </Box>
        )}
        <Typography variant="h4" sx={{ color: '#fff', textAlign: 'center' }}>
          Verify Your Identity
        </Typography>
        <Stack sx={{ backgroundColor: '#fff', padding: '24px', borderRadius: '5px' }} spacing={4}>
          <Stack spacing={1}>
            <Typography>To keep your account secure, we verify your identity.</Typography>
            <Typography>Enter the code generated by your authenticator app.</Typography>
          </Stack>
          <Stack spacing={2}>
            <TextField
              fullWidth
              id="code"
              placeholder="6-digit Verification Code"
              type="number"
              value={code}
              onChange={(e) => handleCodeChange(e.target.value)}
            />
            <Button variant="contained" fullWidth onClick={handleVerifyCode}>
              Verify
            </Button>
          </Stack>
        </Stack>
      </Stack>
    </Page>
  );
}

export default Verify2FA;
