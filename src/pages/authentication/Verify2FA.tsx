import { Typography, Stack, TextField, Button } from '@material-ui/core';
import Page from 'components/Page';
import useAuth from 'hooks/useAuth';
import { useSnackbar } from 'notistack5';
import { useEffect, useState } from 'react';
import axios from 'utils/axios';

function Verify2FA() {
  const [code, setCode] = useState('');
  const [verificationCode, setVerificationCode] = useState<any>();
  const { enqueueSnackbar } = useSnackbar();
  const { setIs2faVerified } = useAuth();

  useEffect(() => {
    axios
      .post(`verification_codes.json`)
      .then((response) => {
        setVerificationCode(response.data.verification_code);
      })
      .catch((error) => {
        enqueueSnackbar('Something went wrong!', { variant: 'error' });
      });
  }, []);

  const handleVerifyCode = () => {
    axios
      .post(`verification_codes/${verificationCode?.id}/verify.json`, {
        code
      })
      .then((response) => {
        setIs2faVerified();
        enqueueSnackbar('Successfully verified!', { variant: 'success' });
      })
      .catch((error) => {
        enqueueSnackbar('Something went wrong!', { variant: 'error' });
      });
  };

  const handleCancelCode = () => {
    axios
      .delete(`verification_codes/${verificationCode?.id}.json`)
      .then((response) => {})
      .catch((error) => {
        enqueueSnackbar('Something went wrong!', { variant: 'error' });
      });
  };

  return (
    <Page
      title="Sphere | Verification"
      sx={{
        display: 'flex',
        justifyContent: 'center',
        alignItems: 'center',
        backgroundColor: '#12125C',
        width: '100%',
        height: '100%'
      }}
    >
      <Stack spacing={2}>
        <Typography variant="h4" sx={{ color: '#fff', textAlign: 'center' }}>
          Verify Your Identity
        </Typography>
        <Stack sx={{ backgroundColor: '#fff', padding: '24px', borderRadius: '5px' }} spacing={4}>
          <Stack spacing={1}>
            <Typography>To keep your account secure, we verify your identity.</Typography>
            <Typography>Enter the code generated by your authenticator app.</Typography>
          </Stack>
          <Stack spacing={2}>
            <TextField
              fullWidth
              id="code"
              placeholder="Verification Code"
              type="number"
              value={code}
              onChange={(e) => setCode(e.target.value)}
            />
            <Stack spacing={2} direction={{ xs: 'column', md: 'row' }} width="100%">
              <Button variant="outlined" fullWidth onClick={handleCancelCode}>
                Cancel
              </Button>
              <Button variant="contained" fullWidth onClick={handleVerifyCode}>
                Verify
              </Button>
            </Stack>
          </Stack>
        </Stack>
      </Stack>
    </Page>
  );
}

export default Verify2FA;
